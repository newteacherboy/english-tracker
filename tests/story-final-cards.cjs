const assert=require('node:assert/strict');
const {create,normalize,unique}=require('../ingilizce/story-final-cards.js');
assert.equal(normalize('  Hello!  '),'hello');
assert.equal(normalize('I’m Papi.'),"i'm papi");
assert.equal(unique([{en:'Hello!',tr:'Merhaba'},{en:'hello',tr:'Selam'}]).length,1);
const deck=[{en:'Hello!',tr:'Merhaba!'},{en:'My name is Papi.',tr:'Benim adım Papi.'}];
let run=create(deck);
assert.equal(run.submit('').status,'empty');
assert.equal(run.snapshot().attempts,0);
assert.equal(run.submit('no').status,'hint');
assert.equal(run.snapshot().attempts,1);
assert.equal(run.submit('wrong').status,'reveal');
assert.deepEqual(run.snapshot().missed,[0]);
assert.equal(run.current().en,deck[1].en);
run=create(deck,run.snapshot());
assert.equal(run.submit('MY NAME IS PAPI').status,'correct');
assert.equal(run.snapshot().done,true);
assert.equal(run.submit('anything').status,'finished');
console.log('PASS final cards two attempts, hint, reveal, restore and normalization');
