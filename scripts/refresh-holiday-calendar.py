#!/usr/bin/env python3
"""Refresh official Diyanet dates and replace three artistic statue depictions with a real historical Atatürk photo."""
import datetime as dt
import io
import json
import os
import re
import sys
import unicodedata
import urllib.request
from pathlib import Path

ROOT=Path(__file__).resolve().parents[1]
ART=ROOT/'ingilizce'/'holiday-splashes'
SOURCE='https://vakithesaplama.diyanet.gov.tr/icerik.php?icerik='
PHOTO='https://upload.wikimedia.org/wikipedia/commons/a/a8/Ataturk1930s.jpg'
YEARS={2026:153,2027:154,**{y:185+(y-2028) for y in range(2028,2036)}}
MONTH={'OCAK':1,'SUBAT':2,'MART':3,'NISAN':4,'MAYIS':5,'HAZIRAN':6,'TEMMUZ':7,'AGUSTOS':8,'EYLUL':9,'EKIM':10,'KASIM':11,'ARALIK':12}
def normalize(s):
    return ''.join(c for c in unicodedata.normalize('NFKD',s.upper().replace('İ','I').replace('ı','I')) if not unicodedata.combining(c))
def get(url):
    req=urllib.request.Request(url,headers={'User-Agent':'DijiMedu-HolidayCalendar/1.0 (noncommercial educational app)'})
    with urllib.request.urlopen(req,timeout=18) as r:return r.read()
def parse_html(html):
    from bs4 import BeautifulSoup
    soup=BeautifulSoup(html,'html.parser')
    out=[]
    for tr in soup.find_all('tr'):
        cols=[c.get_text(' ',strip=True) for c in tr.find_all(['td','th'],recursive=False)]
        if len(cols)<7:continue
        label=normalize(cols[-1]);txt=normalize(cols[4])
        dateMatch=re.search(r'(OCAK|SUBAT|MART|NISAN|MAYIS|HAZIRAN|TEMMUZ|AGUSTOS|EYLUL|EKIM|KASIM|ARALIK)\s*-\s*(20\d{2})',txt)
        dayMatch=re.match(r'\s*(\d{1,2})',cols[3])
        if not dateMatch or not dayMatch:continue
        day=int(dayMatch.group(1))
        try:dayIso=dt.date(int(dateMatch.group(2)),MONTH[dateMatch.group(1)],day).isoformat()
        except ValueError:continue
        if 'RAMAZAN BASLANGICI' in label:out.append(('ramadan',dayIso))
        if 'RAMAZAN BAY' in label and re.search(r'\b1\s*[.\)]',label):out.append(('ramadanEid',dayIso))
        if 'KURBAN BAY' in label and re.search(r'\b1\s*[.\)]',label):out.append(('kurbanEid',dayIso))
    return out
def nextday(s,n):return (dt.date.fromisoformat(s)+dt.timedelta(days=n)).isoformat()
def update_dates():
    records={'ramadan':set(),'ramadanEid':set(),'kurbanEid':set()}
    failures=[]
    # Discover future official-year links as Diyanet adds 2036, 2037, etc.
    try:
        from bs4 import BeautifulSoup
        nav=BeautifulSoup(get('https://vakithesaplama.diyanet.gov.tr/').decode('utf-8','replace'),'html.parser')
        for a in nav.find_all('a',href=True):
            label=normalize(a.get_text(' ',strip=True))
            match=re.search(r'(20\\d{2})\\s+YILI?\\s+DINI\\s+GUNLER',label)
            ident=re.search(r'icerik=(\\d+)',a['href'])
            if match and ident:
                y=int(match.group(1))
                if 2026<=y<=2099:YEARS[y]=int(ident.group(1))
    except Exception as exc:print('Diyanet navigation temporarily unavailable:',exc)
    for year,id in sorted(YEARS.items()):
        try:
            text=get(SOURCE+str(id)).decode('utf-8','replace')
            if f'{year} D' not in normalize(text):raise RuntimeError('year mismatch')
            rows=parse_html(text)
            if not rows:raise RuntimeError('no rows')
            for kind,date in rows:records[kind].add(date)
            print(year,rows)
        except Exception as exc:
            failures.append((year,str(exc)))
    path=ART/'dates.json'
    old=json.loads(path.read_text()) if path.exists() else {'periods':{}}
    if not records['ramadan'] or not records['ramadanEid'] or not records['kurbanEid']:
        raise RuntimeError('Diyanet source unavailable; existing calendar preserved '+repr(failures))
    periods={}
    eid=sorted(records['ramadanEid'])
    periods['ramadan']=[]
    for begin in sorted(records['ramadan']):
        end=next((d for d in eid if begin<d<=nextday(begin,32)),None)
        if end:periods['ramadan'].append([begin,nextday(end,-1)])
    periods['ramadanEid']=[[d,nextday(d,2)] for d in eid]
    periods['kurbanEid']=[[d,nextday(d,3)] for d in sorted(records['kurbanEid'])]
    # Do not erase known dates when a year is temporarily unreachable.
    for key,items in old.get('periods',{}).items():
        known={tuple(p) for p in periods.get(key,[])}
        known.update(tuple(p) for p in items if p[0][:4] in {str(y) for y,_ in failures})
        periods[key]=[list(p) for p in sorted(known)]
    oldPeriod=old.get('periods')
    if periods==oldPeriod:
        print('No calendar date changes');return
    calendar={'source':'https://vakithesaplama.diyanet.gov.tr/','verified':dt.date.today().isoformat(),'periods':periods}
    path.write_text(json.dumps(calendar,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    (ART/'dates.js').write_text('/* Official Diyanet dates, regenerated by GitHub Actions. */\nwindow.DM_HOLIDAY_DATES='+json.dumps(calendar,ensure_ascii=False,separators=(',',':'))+';\n',encoding='utf-8')
    print('Calendar updated',len(periods['ramadan']),'Ramadan periods;',failures)
def repair_images():
    marker=ART/'.archive-photo-2026-applied'
    if marker.exists():
        print('Historical Atatürk photo edits were already applied; skipping.');return
    from PIL import Image,ImageFilter,ImageOps
    try:photo=Image.open(io.BytesIO(get(PHOTO))).convert('RGB')
    except Exception as exc:
        print('Photo download failed, original artwork retained:',exc);return
    # Position is a soft-edged artwork substitution; the original pixels outside the named region are unchanged.
    locations={
     '19-mayis-1.jpg':(.775,.12,.99,.41),
     '19-mayis-2.jpg':(.165,.30,.435,.545),
     '10-kasim-2.jpg':(.79,.04,.99,.35)
    }
    # Archive source itself remains untouched; never call generated faces 'authentic photos'.
    changed=False
    for name,coords in locations.items():
        path=ART/name
        if not path.exists():continue
        original=Image.open(path).convert('RGB')
        w,h=original.size
        box=tuple(round(v*(w if i%2==0 else h)) for i,v in enumerate(coords))
        size=(box[2]-box[0],box[3]-box[1])
        portrait=ImageOps.fit(photo,size,method=Image.Resampling.LANCZOS,centering=(.5,.24))
        portrait=portrait.convert('RGB')
        mask=Image.new('L',size,0)
        from PIL import ImageDraw
        draw=ImageDraw.Draw(mask)
        pad=max(3,round(min(size)*.05))
        draw.ellipse((pad,pad,size[0]-pad,size[1]-pad),fill=255)
        mask=mask.filter(ImageFilter.GaussianBlur(max(3,round(min(size)*.07))))
        original.paste(portrait,box[:2],mask)
        original.save(path,'JPEG',quality=94,optimize=True,subsampling=0)
        print('Archive photograph composited:',name)
        changed=True
    if changed:marker.write_text('Source: '+PHOTO+'\n',encoding='utf-8')
if __name__=='__main__':
    try:update_dates()
    except Exception as exc:print('Calendar refresh warning (kept prior verified dates):',exc)
    repair_images()
